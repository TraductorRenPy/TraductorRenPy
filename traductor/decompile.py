"""Paso 3: decompilar .rpyc a .rpy con unrpyc (MIT).

unrpyc viene incluido en `vendor/unrpyc` (con su licencia); también se puede
indicar otra ruta de `unrpyc.py` (o de la carpeta que lo contiene). Escribe cada
.rpy junto a su .rpyc, por eso se ejecuta solo sobre la carpeta de scripts
extraídos, nunca sobre el juego.

Dentro del .exe no hay un intérprete de Python aparte: el programa se vuelve a
llamar a sí mismo con `--unrpyc-run` (ver `main.py`).
"""

import re
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import List, Optional, Tuple

from .common import Cancelled, LogFn, noop_log
from .settings import FROZEN, RESOURCE_DIR

DEFAULT_LOCATIONS = (RESOURCE_DIR / "vendor" / "unrpyc",)


def unrpyc_command(unrpyc: Path, target: Path) -> List[str]:
    """Orden para ejecutar unrpyc sobre `target` (con o sin .exe empaquetado)."""
    if FROZEN:
        return [sys.executable, "--unrpyc-run", str(unrpyc), str(target)]
    return [sys.executable, str(unrpyc), str(target)]


def find_unrpyc(configured: str = "") -> Optional[Path]:
    candidates = [Path(configured)] if configured else []
    candidates += list(DEFAULT_LOCATIONS)
    for c in candidates:
        if c.is_file() and c.name.lower().endswith(".py"):
            return c
        if (c / "unrpyc.py").is_file():
            return c / "unrpyc.py"
    return None


def decompile_dir(
    unrpyc: Path,
    scripts_dir: Path,
    log: LogFn = noop_log,
    cancel: Optional[threading.Event] = None,
    timeout: float = 1800,
) -> Tuple[int, List[str]]:
    """Decompila todos los .rpyc de scripts_dir sin .rpy. Devuelve (ok, fallidos)."""
    pending = [
        p
        for p in scripts_dir.rglob("*")
        if p.suffix.lower() in (".rpyc", ".rpymc")
        and not p.with_suffix(p.suffix[:-1]).exists()
    ]
    if not pending:
        log("No hay .rpyc pendientes de decompilar.")
        return 0, []
    log(f"Decompilando {len(pending)} archivos con {unrpyc} ...")
    cmd = unrpyc_command(unrpyc, scripts_dir)
    proc = subprocess.Popen(
        cmd,
        cwd=str(unrpyc.parent),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        stdin=subprocess.DEVNULL,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )

    counts = {"done": 0, "old": 0}

    def reader():
        # unrpyc imprime una o más líneas por archivo; se resume a un
        # avance periódico, un conteo de advertencias y los errores reales.
        for line in proc.stdout:
            line = line.strip()
            if not line:
                continue
            if line.startswith("Decompiling "):
                counts["done"] += 1
                if counts["done"] % 25 == 0:
                    log(f"  {counts['done']}/{len(pending)} ...")
            elif "generated by ren'py" in line:
                counts["old"] += 1
            elif "will still be attempted" in line or "decompilation might occur" in line:
                continue  # resto de la advertencia de versión (ya contada)
            elif re.search(r"error|failed|traceback|exception", line, re.I):
                log("  " + line)

    t = threading.Thread(target=reader, daemon=True)
    t.start()
    start = time.monotonic()
    try:
        while proc.poll() is None:
            if cancel is not None and cancel.is_set():
                raise Cancelled()
            if time.monotonic() - start > timeout:
                raise TimeoutError("unrpyc no terminó a tiempo.")
            time.sleep(0.2)
    except BaseException:
        proc.kill()
        raise
    finally:
        t.join(timeout=2)

    if counts["old"]:
        log(
            f"  Aviso: {counts['old']} archivos parecen de Ren'Py 7 o anterior; "
            "unrpyc apunta a Ren'Py 8. Es solo una advertencia, se revisa el resultado abajo."
        )
    failed = [
        p.relative_to(scripts_dir).as_posix()
        for p in pending
        if not p.with_suffix(p.suffix[:-1]).exists()
    ]
    return len(pending) - len(failed), failed
